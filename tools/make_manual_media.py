"""Create the neutral media used for the user-manual screenshots.

    python tools/make_manual_media.py <media dir>

Everything is generated by FFmpeg (must be on PATH): two colour gradients
as photos, a test-pattern video with a tone, and two short tones as music.
No personal photos or recordings ever end up in the manual.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

JOBS = {
    "poster.jpg": ["-f", "lavfi", "-i",
                   "gradients=s=1920x1080:c0=0x064e3b:c1=0x0ea5e9:c2=0xfef3c7:nb_colors=3:x0=0:y0=1080:x1=1920:y1=0",
                   "-frames:v", "1"],
    "stage_backdrop.jpg": ["-f", "lavfi", "-i",
                           "gradients=s=1920x1080:c0=0x3b0764:c1=0xdb2777:c2=0xf59e0b:nb_colors=3:x0=0:y0=0:x1=1920:y1=1080",
                           "-frames:v", "1"],
    "opening_video.mp4": ["-f", "lavfi", "-i", "testsrc2=s=1280x720:r=25:d=12",
                          "-f", "lavfi", "-i", "sine=frequency=330:duration=12",
                          "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest"],
    "overture.mp3": ["-f", "lavfi", "-i", "sine=frequency=440:duration=30", "-b:a", "128k"],
    "finale.mp3": ["-f", "lavfi", "-i", "sine=frequency=262:duration=20", "-b:a", "128k"],
}


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    ffmpeg = shutil.which("ffmpeg")
    if ffmpeg is None:
        print("FFmpeg not found on PATH")
        return 1
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    for name, args in JOBS.items():
        target = out / name
        subprocess.run([ffmpeg, "-y", "-loglevel", "error", *args, str(target)], check=True)
        print("wrote", target)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
